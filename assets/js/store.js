/* ============================================================
   Valley Feast — data store
   ------------------------------------------------------------
   Reads the published database (data/menu-data.js) and overlays
   any local working copy saved by the admin studio, so edits
   made in /admin are live everywhere on this device instantly.
   Publishing = exporting a fresh menu-data.js from the admin.
   ============================================================ */

(function () {
  const KEY = 'vf-data-v1';

  function published() {
    return window.VF_DATA || { version: 0, settings: {}, categories: [], items: [] };
  }

  function load() {
    try {
      const raw = localStorage.getItem(KEY);
      if (!raw) return structuredClone(published());
      const local = JSON.parse(raw);
      // A newer published file wins over an older local draft.
      if ((local.version || 0) < (published().version || 0)) {
        localStorage.removeItem(KEY);
        return structuredClone(published());
      }
      return local;
    } catch {
      return structuredClone(published());
    }
  }

  function save(data) {
    localStorage.setItem(KEY, JSON.stringify(data));
  }

  function reset() {
    localStorage.removeItem(KEY);
  }

  function money(v, settings) {
    if (v == null || v === '') return null;
    const cur = (settings || load().settings).currency || '$';
    const n = Number(v);
    return cur + (Number.isInteger(n) ? n : n.toFixed(2));
  }

  function sortedCategories(data) {
    return [...data.categories].sort((a, b) => (a.order || 0) - (b.order || 0));
  }

  function itemsFor(data, catId, includeUnavailable) {
    return data.items
      .filter(i => i.category === catId && (includeUnavailable || i.available !== false))
      .sort((a, b) => (a.order || 0) - (b.order || 0));
  }

  function exportFile(data) {
    const clean = structuredClone(data);
    clean.version = (clean.version || 0) + 1;
    const body =
      '/* Valley Feast Kitchen Delight — published menu database.\n' +
      '   Generated by the admin studio on ' + new Date().toLocaleString() + '.\n' +
      '   Replace data/menu-data.js with this file to publish. */\n\n' +
      'window.VF_DATA = ' + JSON.stringify(clean, null, 2) + ';\n';
    return { body, version: clean.version };
  }

  window.VFStore = { load, save, reset, money, sortedCategories, itemsFor, exportFile, KEY };
})();
